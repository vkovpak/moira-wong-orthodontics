define( 'MW_DIR', get_template_directory() );

/**
 * Theme setup.
 */
function mw_setup() {
	load_theme_textdomain( 'moira-wong-orthodontics', MW_DIR . '/languages' );

	add_theme_support( 'wp-block-styles' );
	add_theme_support( 'editor-styles' );
	add_theme_support( 'responsive-embeds' );
	add_theme_support( 'html5', array( 'search-form', 'comment-form', 'comment-list', 'gallery', 'caption', 'style', 'script' ) );

	// Theme-wide styles (header, footer, utilities), also loaded in the editor canvas.
	add_editor_style( 'build/theme/index.css' );
	add_editor_style( 'build/theme/editor.css' );
}
add_action( 'after_setup_theme', 'mw_setup' );

/**
 * Theme-wide stylesheet and script compiled from src/theme by wp-scripts (see webpack.config.js).
 */
function mw_enqueue_theme_assets() {
	$css = MW_DIR . '/build/theme/index.css';

	if ( file_exists( $css ) ) {
		wp_enqueue_style(
			'mw-theme',
			get_template_directory_uri() . '/build/theme/index.css',
			array(),
			(string) filemtime( $css )
		);
	}

	$js    = MW_DIR . '/build/theme/index.js';
	$asset = MW_DIR . '/build/theme/index.asset.php';

	if ( file_exists( $js ) && file_exists( $asset ) ) {
		$meta = require $asset;
		wp_enqueue_script( 'mw-theme', get_template_directory_uri() . '/build/theme/index.js', $meta['dependencies'], (string) filemtime( $js ), true );
	}
}
add_action( 'wp_enqueue_scripts', 'mw_enqueue_theme_assets' );

/**
 * Groups all mw/* blocks together in the inserter.
 */
function mw_block_categories( $categories ) {
	return array_merge(
		array(
			array(
				'slug'  => 'mw',
				'title' => __( 'Moira Wong', 'moira-wong-orthodontics' ),
			),
		),
		$categories
	);
}
add_filter( 'block_categories_all', 'mw_block_categories' );

/**
 * Registers all mw/* blocks in one call via the manifest generated by `wp-scripts build`.
 */
function mw_register_blocks() {
	$manifest = MW_DIR . '/build/blocks-manifest.php';

	if ( file_exists( $manifest ) ) {
		wp_register_block_types_from_metadata_collection( MW_DIR . '/build', $manifest );
	}
}
add_action( 'init', 'mw_register_blocks' );

/**
 * Per-page switch for the global footer logos (default: shown). Edited in the page settings panel,
 * see src/theme/editor.js.
 */
function mw_register_meta() {
	register_post_meta(
		'page',
		'mw_hide_footer_logos',
		array(
			'show_in_rest'  => true,
			'single'        => true,
			'type'          => 'boolean',
			'default'       => false,
			'auth_callback' => function () {
				return current_user_can( 'edit_pages' );
			},
		)
	);
}
add_action( 'init', 'mw_register_meta' );

/**
 * Hides the footer's logo strip (the mw/logos block marked with the mw-footer-logos class) on pages
 * that switched it off. Logo strips placed in the page content are never touched.
 */
function mw_maybe_hide_footer_logos( $block_content, $parsed_block ) {
	$classes = $parsed_block['attrs']['className'] ?? '';

	if ( false === strpos( $classes, 'mw-footer-logos' ) ) {
		return $block_content;
	}

	if ( is_singular( 'page' ) && get_post_meta( get_queried_object_id(), 'mw_hide_footer_logos', true ) ) {
		return '';
	}

	return $block_content;
}
add_filter( 'render_block_mw/logos', 'mw_maybe_hide_footer_logos', 10, 2 );

/**
 * Editor-only script: the page settings panel and the logo size lock.
 */
function mw_enqueue_editor_script() {
	$js    = MW_DIR . '/build/theme/editor.js';
	$asset = MW_DIR . '/build/theme/editor.asset.php';

	if ( file_exists( $js ) && file_exists( $asset ) ) {
		$meta = require $asset;
		wp_enqueue_script( 'mw-editor', get_template_directory_uri() . '/build/theme/editor.js', $meta['dependencies'], (string) filemtime( $js ), true );
	}

	// add_editor_style() only reaches the canvas iframe; the sidebar (alt text fields) needs its own copy.
	$css = MW_DIR . '/build/theme/editor.css';
	if ( file_exists( $css ) ) {
		wp_enqueue_style( 'mw-editor', get_template_directory_uri() . '/build/theme/editor.css', array( 'wp-edit-blocks' ), (string) filemtime( $css ) );
	}

	// Hides the Site Logo's "Image width" setting while the header or footer logo is selected (see src/theme/editor.js).
	wp_add_inline_style( 'wp-block-editor', 'body.mw-logo-size-locked .block-editor-block-inspector .components-tools-panel-item:has(input[type="range"]) { display: none; }' );
}
add_action( 'enqueue_block_editor_assets', 'mw_enqueue_editor_script' );

/**
 * Rewrites build asset versions to each file's own filemtime, so edited CSS/JS busts the cache automatically.
 */
function mw_bust_block_asset_cache( $src ) {
	if ( ! $src ) {
		return $src;
	}

	$build_uri = get_template_directory_uri() . '/build/';
	if ( 0 !== strpos( $src, $build_uri ) ) {
		return $src;
	}

	$file = MW_DIR . '/build/' . substr( strtok( $src, '?' ), strlen( $build_uri ) );

	if ( ! file_exists( $file ) ) {
		return $src;
	}

	return add_query_arg( 'ver', filemtime( $file ), remove_query_arg( 'ver', $src ) );
}
add_filter( 'style_loader_src', 'mw_bust_block_asset_cache' );
add_filter( 'script_loader_src', 'mw_bust_block_asset_cache' );

